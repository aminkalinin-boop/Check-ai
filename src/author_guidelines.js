function authorGuidelineMatches(text, limit=12) {
  const s=String(text||''), hits=[];
  for(const rule of CHECK_AI_AUTHOR_RULES){
    for(const match of s.matchAll(rule.re)){
      hits.push({id:rule.id,kind:rule.kind,section:rule.section,title:rule.title,
        quote:match[0].replace(/\s+/g,' ').slice(0,95),at:match.index,
        why:rule.why,action:rule.action,source:CHECK_AI_AUTHOR_STANDARD.source});
      if(hits.length>250)break;
    }
    rule.re.lastIndex=0;
  }
  hits.sort((a,b)=>a.at-b.at||a.id.localeCompare(b.id));
  return hits.slice(0,limit);
}
function authorGuidelineAudit(res) {
  const paras=(res.paras||[]).filter(p=>p && p.words>=5 && !p.bib && !p.toc && !p.heading && !p.inBox && !p.inTable);
  const groups={formula:0,language:0,term:0,method:0}, examples=[];
  let marked=0, matches=0;
  for(const p of paras){
    const found=authorGuidelineMatches(p.text,25);
    p.authorGuidelineIds=[...new Set(found.map(m=>m.id))];
    if(found.length)marked++;
    for(const f of found){
      matches++;
      groups[f.kind]++;
      if(examples.length<120)examples.push({para:p.i,title:f.title,quote:f.quote,kind:f.kind,section:f.section,reason:f.why,action:f.action});
    }
  }
  const result={version:CHECK_AI_AUTHOR_STANDARD.version,source:CHECK_AI_AUTHOR_STANDARD.source,
    limits:CHECK_AI_AUTHOR_STANDARD.limits,ruleCount:CHECK_AI_AUTHOR_RULES.length,
    paragraphsReviewed:paras.length,paragraphsWithNotes:marked,matches,byKind:groups,examples,
    verdictImpact:'none',scope:'Стилистическая и предметная редактура; не вероятность авторства.'};
  if(!res.stats)res.stats={};
  res.stats.authorGuidelines=result;
  return result;
}
function authorMarkedGuidance(paragraph, selectedText) {
  const selected=String(selectedText||'').trim();
  const exact=authorGuidelineMatches(selected,5);
  const broader=exact.length?[]:authorGuidelineMatches(paragraph?.text||'',3);
  const focus=exact[0]||null;
  return {primary:focus,selected:exact,paragraphOnly:broader,
    notice:exact.length?'Правило обнаружено в точных границах выделения.':'Внутри выделения авторская конструкция не установлена; замечания к остальному абзацу отдельно.'};
}
